test('clearAll empties every store, and the library keeps working afterwards', async () => {
  const lib = await open()
  const a = await lib.createCreation(base), b = await lib.createCreation({ ...base, name: 'b' })
  await lib.setDraft(a.id, { code: 'A*', mode: 'dweet', runMode: 'auto', settings: a.settings })
  await lib.deleteCreation(b.id); await lib.purgeCreation(b.id)
  await lib.setKV('lastImage', 'x')
  await lib.clearAll()
  expect(await lib.listCreations({ includeDeleted: true })).toEqual([])
  expect(await lib.listVersions(a.id)).toEqual([])
  expect(await lib.getDraft(a.id)).toBeNull()
  expect(await lib.listTombstones()).toEqual([])
  expect(await lib.getKV('lastImage')).toBeNull()
  const c = await lib.createCreation(base)
  expect(await lib.listCreations()).toHaveLength(1)
  expect(c.versionCount).toBe(1)
})

import 'fake-indexeddb/auto'
import { test, expect } from 'vitest'
import { openLibrary, DEFAULT_CREATION_SETTINGS } from '../../src/library/library.js'
let n = 0, clock = 1000
const open = () => openLibrary({ dbName: 'lib' + n++, now: () => clock++ })
const base = { name: 'spiral', mode: 'dweet', code: 'a' }

test('create makes v1; save appends versions, updates head and clears draft', async () => {
  const lib = await open()
  const c = await lib.createCreation(base)
  expect(c.versionCount).toBe(1)
  await lib.setDraft(c.id, { code: 'b', mode: 'dweet', runMode: 'auto', settings: c.settings })
  const v2 = await lib.saveVersion(c.id, { code: 'b', mode: 'dweet', runMode: 'auto', settings: c.settings, thumbnail: null })
  expect(v2.n).toBe(2)
  expect((await lib.getCreation(c.id)).headVersionId).toBe(v2.id)
  expect(await lib.getDraft(c.id)).toBeNull()
  expect((await lib.listVersions(c.id)).map(v => v.code)).toEqual(['b', 'a'])
  expect(await lib.getKV('savesSinceExport')).toBe(1)
})
test('fork copies the chosen version and records its parent', async () => {
  const lib = await open()
  const c = await lib.createCreation(base)
  const [v1] = await lib.listVersions(c.id)
  await lib.saveVersion(c.id, { ...base, runMode: 'auto', settings: c.settings, code: 'z', thumbnail: null })
  const f = await lib.fork(c.id, v1.id)
  expect(f.name).toBe('spiral fork')
  expect(f.parentId).toBe(c.id)
  expect(f.parentVersionId).toBe(v1.id)
  expect((await lib.listVersions(f.id))[0].code).toBe('a')
})
test('drafts are per creation', async () => {
  const lib = await open()
  const a = await lib.createCreation(base), b = await lib.createCreation({ ...base, name: 'b' })
  await lib.setDraft(a.id, { code: 'A*', mode: 'dweet', runMode: 'auto', settings: a.settings })
  expect((await lib.getDraft(a.id)).code).toBe('A*')
  expect(await lib.getDraft(b.id)).toBeNull()
})
test('delete hides, restore returns, purge leaves a tombstone', async () => {
  const lib = await open()
  const c = await lib.createCreation(base)
  await lib.deleteCreation(c.id)
  expect(await lib.listCreations()).toHaveLength(0)
  expect(await lib.listCreations({ includeDeleted: true })).toHaveLength(1)
  await lib.restoreCreation(c.id)
  expect(await lib.listCreations()).toHaveLength(1)
  await lib.deleteCreation(c.id); await lib.purgeCreation(c.id)
  expect(await lib.getCreation(c.id)).toBeNull()
  expect(await lib.listVersions(c.id)).toHaveLength(0)
  expect((await lib.listTombstones()).map(t => t.id)).toEqual([c.id])
})
test('defaults, listing order and updatedAt rules', async () => {
  const lib = await open()
  const a = await lib.createCreation(base)
  expect(a.runMode).toBe('auto')
  expect(a.settings).toEqual(DEFAULT_CREATION_SETTINGS)
  expect(a.thumbnail).toBeNull()
  expect(a.deletedAt).toBeNull()
  expect(await lib.getKV('savesSinceExport') ?? 0).toBe(0)
  const b = await lib.createCreation({ ...base, name: 'b' })
  expect((await lib.listCreations()).map(c => c.id)).toEqual([b.id, a.id])
  await lib.setDraft(a.id, { code: 'x', mode: 'dweet', runMode: 'auto', settings: a.settings })
  await lib.getDraft(a.id)
  await lib.discardDraft(a.id)
  expect((await lib.getCreation(a.id)).updatedAt).toBe(a.updatedAt)
  await lib.rename(a.id, 'renamed')
  const r = await lib.getCreation(a.id)
  expect(r.name).toBe('renamed')
  expect(r.updatedAt).toBeGreaterThan(a.updatedAt)
  await lib.deleteCreation(a.id)
  const d = await lib.getCreation(a.id)
  expect(d.deletedAt).toBeGreaterThan(0)
  expect(d.updatedAt).toBe(r.updatedAt)
  expect((await lib.listTombstones())[0]).toEqual({ id: a.id, deletedAt: d.deletedAt })
  await lib.restoreCreation(a.id)
  const rr = await lib.getCreation(a.id)
  expect(rr.deletedAt).toBeNull()
  expect(rr.updatedAt).toBeGreaterThan(d.updatedAt)
})
test('saveVersion keeps the thumbnail unless given a Blob', async () => {
  const lib = await open()
  const c = await lib.createCreation(base)
  const args = { code: 'b', mode: 'dweet', runMode: 'auto', settings: c.settings }
  const blob = new Blob(['x'], { type: 'image/png' })
  await lib.saveVersion(c.id, { ...args, thumbnail: blob })
  expect((await lib.getCreation(c.id)).thumbnail).toBeInstanceOf(Blob)
  await lib.saveVersion(c.id, { ...args, code: 'c', thumbnail: null })
  const cur = await lib.getCreation(c.id)
  expect(cur.thumbnail).toBeInstanceOf(Blob)
  expect(cur.versionCount).toBe(3)
})
test('kv and raw helpers', async () => {
  const lib = await open()
  expect(await lib.getKV('nope')).toBeNull()
  await lib.setKV('k', { a: 1 })
  expect(await lib.getKV('k')).toEqual({ a: 1 })
  await lib.raw.put('creations', { id: 'orig', name: 'o', updatedAt: 5 })
  expect((await lib.raw.get('creations', 'orig')).updatedAt).toBe(5)
  await lib.raw.put('versions', { id: 'v', creationId: 'orig', n: 1 })
  expect(await lib.raw.getAllByIndex('versions', 'creationId', 'orig')).toHaveLength(1)
  expect(await lib.raw.getAll('creations')).toHaveLength(1)
  await lib.raw.del('creations', 'orig')
  expect(await lib.raw.get('creations', 'orig')).toBeNull()
})
